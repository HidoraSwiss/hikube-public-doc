/**
 * Les libellés générés se répètent d'un service à l'autre (« Create user »…) :
 * une clé unique par entrée évite les conflits de clés de traduction.
 */
function withUniqueKeys(items) {
  return items.map((item) => {
    if (item.type === "category") {
      return {
        ...item,
        key: `api-reference-${item.label}`,
        items: withUniqueKeys(item.items),
      };
    }
    if (item.type === "doc") {
      return { ...item, key: item.id };
    }
    return item;
  });
}

/**
 * Helper: génère les items Diátaxis pour un service.
 * Le dossier how-to/ utilise autogenerated + generated-index
 * pour fonctionner même quand il est vide.
 * Il n'y a plus de page api-reference par service : la référence de l'API
 * publique est générée depuis la spécification OpenAPI (catégorie « API »,
 * docs/api/reference/, `npm run gen-api-docs`).
 */
function diatasisItems(basePath, extraItems) {
  const key = `how-to-${basePath.replace(/\//g, "-")}`;
  return [
    `${basePath}/overview`,
    `${basePath}/concepts`,
    `${basePath}/quick-start`,
    {
      type: "category",
      label: "Guides pratiques",
      key,
      link: { type: "generated-index", title: "Guides pratiques" },
      items: [{ type: "autogenerated", dirName: `${basePath}/how-to` }],
    },
    ...(extraItems || []),
    `${basePath}/faq`,
    `${basePath}/troubleshooting`,
  ];
}

